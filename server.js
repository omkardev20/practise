function serveStatic(req, res, pathname) {
  if (pathname === "/") {
    const lessons = fs.readdirSync(ROOT).filter((d) => LESSON_RE.test(d)).sort();
    res.writeHead(200, { "Content-Type": TYPES[".html"] });
    res.end(renderDashboardHtml(lessons));
    return;
  }
  let file = path.normalize(path.join(ROOT, decodeURIComponent(pathname)));
  if (!file.startsWith(ROOT) || path.basename(file).startsWith(".")) {
    res.writeHead(403).end("Forbidden");
    return;
  }
  if (fs.existsSync(file) && fs.statSync(file).isDirectory()) file = path.join(file, "index.html");
  fs.readFile(file, (err, data) => {
    if (err) {
      res.writeHead(404).end("Not found");
      return;
    }
    res.writeHead(200, { "Content-Type": TYPES[path.extname(file)] || "application/octet-stream" });
    res.end(data);
  });
}

const server = http.createServer(async (req, res) => {
  setCors(res);
  const url = new URL(req.url, `http://localhost:${PORT}`);

  if (req.method === "OPTIONS") {
    res.writeHead(204).end();
    return;
  }

  if (url.pathname === "/api/progress" && req.method === "GET") {
    const lesson = url.searchParams.get("lesson") || "";
    if (!LESSON_RE.test(lesson)) return sendJson(res, 400, { error: "bad lesson" });
    return sendJson(res, 200, loadSolutions(lesson));
  }

  if (url.pathname === "/api/save" && req.method === "POST") {
    try {
      const data = JSON.parse(await readBody(req));
      if (!LESSON_RE.test(data.lesson) || !ID_RE.test(data.id) || typeof data.code !== "string") {
        return sendJson(res, 400, { error: "bad data" });
      }
      saveSolution(data);
      console.log(`✅ saved ${data.lesson}/${data.id}`);
      return sendJson(res, 200, { ok: true });
    } catch (err) {
      return sendJson(res, 500, { error: err.message });
    }
  }

  if (req.method === "GET") return serveStatic(req, res, url.pathname);
  res.writeHead(405).end();
});

server.listen(PORT, "127.0.0.1", () => {
  console.log(`Practice server running → http://localhost:${PORT}`);
  console.log("Passed exercises are saved into each lesson's solutions/ folder. Press Ctrl + C to stop.");
});
