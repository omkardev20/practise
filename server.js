// Practice server: serves the lesson pages AND saves every passed exercise as a real file.
// Run:  node server.js   (keep it running while you practise)
// Then open http://localhost:5174  (opening index.html by double-click also works while this runs)
//
// What it writes:
//   <lesson>/solutions/NN-name.js   your code, saved when all tests pass
//   <lesson>/progress.json          which exercises are done
//   PROGRESS.md                     summary of all lessons (read by AI tutors, see CLAUDE.md)

const http = require("http");
const fs = require("fs");
const path = require("path");

const PORT = 5174;
const ROOT = __dirname;
const LESSON_RE = /^\d{2}-[a-z0-9-]+$/;
const ID_RE = /^[A-Za-z0-9]+$/;
const CODE_MARKER = "// ---------- my solution ----------";
const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".md": "text/markdown; charset=utf-8",
};

// ---------- progress files ----------
function progressPath(lesson) {
  return path.join(ROOT, lesson, "progress.json");
}

function readProgress(lesson) {
  try {
    return JSON.parse(fs.readFileSync(progressPath(lesson), "utf8"));
  } catch {
    return { total: 0, exercises: {} };
  }
}

function saveSolution({ lesson, id, num, title, desc, code, total }) {
  const file = `solutions/${String(num).padStart(2, "0")}-${id}.js`;
  const header = [
    `// ${title}`,
    `// ${desc}`,
    `// Passed all tests on ${new Date().toISOString().slice(0, 10)}`,
    CODE_MARKER,
    "",
  ].join("\n");
  fs.mkdirSync(path.join(ROOT, lesson, "solutions"), { recursive: true });
  fs.writeFileSync(path.join(ROOT, lesson, file), header + code.trimEnd() + "\n");

  const progress = readProgress(lesson);
  progress.total = total;
  progress.exercises[id] = {
    num,
    title,
    completedAt: progress.exercises[id]?.completedAt || new Date().toISOString(),
    lastSavedAt: new Date().toISOString(),
    file,
  };
  fs.writeFileSync(progressPath(lesson), JSON.stringify(progress, null, 2) + "\n");
  writeProgressMd();
}

function loadSolutions(lesson) {
  const progress = readProgress(lesson);
  const done = {};
  const code = {};
  for (const [id, info] of Object.entries(progress.exercises)) {
    done[id] = true;
    try {
      const text = fs.readFileSync(path.join(ROOT, lesson, info.file), "utf8");
      const at = text.indexOf(CODE_MARKER);
      code[id] = at === -1 ? text : text.slice(at + CODE_MARKER.length).replace(/^\n+/, "");
    } catch {}
  }
  return { done, code };
}

function writeProgressMd() {
  const lessons = fs
    .readdirSync(ROOT)
    .filter((d) => LESSON_RE.test(d) && fs.existsSync(progressPath(d)))
    .sort();
  const lines = [
    "# My Progress",
    "",
    "_Auto-generated by server.js whenever an exercise passes. Don't edit by hand._",
    "",
    `Last updated: ${new Date().toISOString().slice(0, 16).replace("T", " ")}`,
    "",
  ];
  for (const lesson of lessons) {
    const { total, exercises } = readProgress(lesson);
    const list = Object.values(exercises).sort((a, b) => a.num - b.num);
    lines.push(`## ${lesson} (${list.length} / ${total} done)`, "");
    for (const ex of list) {
      lines.push(`- ✅ ${ex.title}, passed ${ex.completedAt.slice(0, 10)} → [code](${lesson}/${ex.file})`);
    }
    lines.push("");
  }
  fs.writeFileSync(path.join(ROOT, "PROGRESS.md"), lines.join("\n"));
}

// ---------- http ----------
function setCors(res) {
  // The page may be opened from file:// (origin "null"), so allow any origin. Only listens on localhost.
  res.setHeader("Access-Control-Allow-Origin", "*");
  res.setHeader("Access-Control-Allow-Methods", "GET, POST, OPTIONS");
  res.setHeader("Access-Control-Allow-Headers", "Content-Type");
  res.setHeader("Access-Control-Allow-Private-Network", "true");
}

function sendJson(res, status, data) {
  res.writeHead(status, { "Content-Type": TYPES[".json"] });
  res.end(JSON.stringify(data));
}

function readBody(req) {
  return new Promise((resolve, reject) => {
    let body = "";
    req.on("data", (chunk) => {
      body += chunk;
      if (body.length > 1_000_000) reject(new Error("too big"));
    });
    req.on("end", () => resolve(body));
    req.on("error", reject);
  });
}

